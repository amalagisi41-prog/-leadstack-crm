// Writes src/generated/registry.ts: every script in src/videos/ that has a
// generated voice manifest becomes a composition. Run after `npm run voice`.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ids = readdirSync(join(root, "src/videos"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .filter((id) => existsSync(join(root, "src/generated", `${id}.json`)))
  .sort();

const ident = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const lines = [
  "// Generated by scripts/registry.mjs — do not edit by hand.",
  ...ids.flatMap((id) => [
    `import ${ident(id)}Script from "../videos/${id}.json";`,
    `import ${ident(id)}Voice from "./${id}.json";`,
  ]),
  "",
  "export const REGISTRY = [",
  ...ids.map((id) => `  { id: "${id}", script: ${ident(id)}Script, voice: ${ident(id)}Voice },`),
  "];",
  "",
];
writeFileSync(join(root, "src/generated/registry.ts"), lines.join("\n"));
console.log(`registry: ${ids.join(", ")}`);
